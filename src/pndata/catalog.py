"""Generate catalog.sql (views + comments) and the human/agent docs from cards and current builds."""

from __future__ import annotations

from datetime import datetime, timezone

import yaml

from pndata.builds import current_build
from pndata.cards import dataset_cards, source_cards
from pndata.config import GENERATED_DIR, REPO_ROOT, data_root
from pndata.db import SESSION_SETUP, new_connection


def _q(s: str) -> str:
    return "'" + str(s).replace("'", "''") + "'"


def catalog_sql() -> str:
    lines = [f"-- Generated by `pn catalog` at {datetime.now(timezone.utc):%Y-%m-%d %H:%M}Z. Do not edit.",
             SESSION_SETUP]
    for cid, card in sorted(dataset_cards().items()):
        cur = current_build(card)
        if not cur:
            continue
        schema = cid.split(".")[0]
        lines.append(f"CREATE SCHEMA IF NOT EXISTS {schema};")
        lines.append(f"CREATE OR REPLACE VIEW {cid} AS FROM read_parquet({_q(cur['path'])});")
        desc = f"{card.get('title', '')}. {card.get('grain', '')}. Build {cur['build_id']}."
        lines.append(f"COMMENT ON VIEW {cid} IS {_q(desc)};")
        for col in card.get("columns", []):
            if col.get("description"):
                lines.append(f"COMMENT ON COLUMN {cid}.{col['name']} IS {_q(col['description'])};")
    return "\n".join(lines) + "\n"


def write_catalog() -> list[str]:
    root = data_root()
    sql = catalog_sql()
    (root / "catalog.sql").write_text(sql, encoding="utf-8")
    new_connection().execute(sql)  # validate it loads
    return write_docs()


def _coverage(con, cid: str, card: dict) -> str:
    period = (card.get("period") or {}).get("field")
    if not period:
        return ""
    lo, hi = con.sql(f"SELECT min({period}), max({period}) FROM {cid}").fetchone()
    return f"{lo} → {hi}"


def write_docs() -> list[str]:
    GENERATED_DIR.mkdir(parents=True, exist_ok=True)
    (GENERATED_DIR / "datasets").mkdir(exist_ok=True)
    con = new_connection()
    sql_path = data_root() / "catalog.sql"
    if sql_path.exists():
        con.execute(sql_path.read_text(encoding="utf-8"))
    index = ["# Data catalog", "",
             "Generated by `pn catalog`. Query any dataset by ID, e.g. `pn.connect().sql(\"FROM transit.gtfs_stop\")`.", "",
             "| Dataset | Title | Grain | Rows | Built | Access |", "|---|---|---|---|---|---|"]
    written = []
    for cid, card in sorted(dataset_cards().items()):
        cur = current_build(card)
        rows = f"{cur['rows']:,}" if cur else "—"
        built = cur["build_id"] if cur else "not built"
        index.append(f"| [`{cid}`](datasets/{cid}.md) | {card.get('title','')} | {card.get('grain','')} | {rows} | {built} | {card.get('access_mode','')} |")
        page = [f"# `{cid}` — {card.get('title','')}", "",
                card.get("description", "").strip(), "",
                f"- **Grain:** {card.get('grain','')}",
                f"- **Primary key:** {', '.join(card.get('primary_key', [])) or '—'}",
                f"- **Layer / access mode:** {card.get('layer','')} / {card.get('access_mode','')}",
                f"- **Source:** {card.get('source','derived')}",
                f"- **Depends on:** {', '.join(card.get('depends_on', [])) or '—'}",
                f"- **Card:** `{card['_path'].relative_to(REPO_ROOT).as_posix()}`"]
        if cur:
            page += [f"- **Current build:** {cur['build_id']} · {cur['rows']:,} rows · git {cur.get('git_sha')}",
                     f"- **Inputs:** {cur['inputs']}"]
            cov = _coverage(con, cid, card)
            if cov:
                page.append(f"- **Coverage:** {cov}")
        page += ["", "## Columns", "", "| Column | Type | Description |", "|---|---|---|"]
        for c in card.get("columns", []):
            page.append(f"| `{c['name']}` | {c.get('type','')} | {c.get('description','')}{' **(pii)**' if c.get('pii') else ''} |")
        if card.get("parameters"):
            page += ["", "## Parameters", "", "```yaml", yaml.safe_dump(card["parameters"], sort_keys=False, allow_unicode=True).strip(), "```"]
        if card.get("caveats"):
            page += ["", "## Caveats", ""] + [f"- {c.get('date','') + ': ' if isinstance(c, dict) and c.get('date') else ''}{c['text'] if isinstance(c, dict) else c}" for c in card["caveats"]]
        if card.get("license"):
            page += ["", "## License and citation", "", "```yaml", yaml.safe_dump(card["license"], sort_keys=False).strip(), "```"]
        if card.get("example_queries"):
            page += ["", "## Example queries", ""] + [f"- `{q}`" for q in card["example_queries"]]
        (GENERATED_DIR / "datasets" / f"{cid}.md").write_text("\n".join(page) + "\n", encoding="utf-8")
        written.append(cid)
    index += ["", "## Sources", "", "| Source | Publisher | Cadence |", "|---|---|---|"]
    for sid, s in sorted(source_cards().items()):
        index.append(f"| `{sid}` | {s.get('publisher','')} | {(s.get('cadence') or {}).get('ours','') if isinstance(s.get('cadence'), dict) else s.get('cadence','')} |")
    (GENERATED_DIR / "CATALOG.md").write_text("\n".join(index) + "\n", encoding="utf-8")
    return written
